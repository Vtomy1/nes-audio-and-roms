/**
 * Builds an 8KB CHR-ROM binary buffer populated with retro font tiles
 */
export function buildChrRomPatternTable(): Uint8Array {
  const chrRom = new Uint8Array(8192); // 8 KB

  // Pattern table has two 4KB halves ($0000-$0FFF and $1000-$1FFF)
  // Each 8x8 tile is 16 bytes (Plane 0: 8 bytes, Plane 1: 8 bytes)
  for (let code = 32; code <= 126; code++) {
    const char = String.fromCharCode(code);
    const bitmap = BASIC_FONT_8X8[char.toUpperCase()] || BASIC_FONT_8X8[' '];
    const tileIndex = code;
    const tileOffset = tileIndex * 16;

    if (tileOffset + 15 < 4096) {
      for (let y = 0; y < 8; y++) {
        // Plane 0 determines pixel on/off in color 1
        chrRom[tileOffset + y] = bitmap[y] ?? 0;
        // Plane 1 is zero for solid color 1
        chrRom[tileOffset + 8 + y] = 0;
      }
    }
  }

  // Draw audio bar VU meter symbols at indices 128 to 135
  for (let bar = 0; bar < 8; bar++) {
    const tileIndex = 128 + bar;
    const tileOffset = tileIndex * 16;
    for (let y = 0; y < 8; y++) {
      if (7 - y <= bar) {
        chrRom[tileOffset + y] = 0xff;
      }
    }
  }

  return chrRom;
}

/**
 * Generates a complete, authentic, bootable .NES ROM containing:
 * 1. 16-byte iNES or NES 2.0 Header
 * 2. 32 KB PRG-ROM ($8000-$FFFF):
 *    - 6502 Machine Code bootloader & APU DPCM playback engine
 *    - Joypad controller polling ($4016)
 *    - Embedded DPCM audio sample data at $C000
 *    - 6502 Vector Table ($FFFA: NMI, $FFFC: Reset, $FFFE: IRQ)
 * 3. 8 KB CHR-ROM (Graphics pattern tables with 8x8 font and VU meter tiles)
 */
export function buildCompleteNesRom(
  headerConfig: NesHeaderConfig,
  dpcmResult: DpcmConversionResult
): Uint8Array {
  // 1. Build 16-byte Header
  const headerBytes = buildNesHeader(headerConfig);

  // 2. PRG-ROM (32 KB = 32,768 bytes, mapped at CPU $8000-$FFFF)
  const prgRomSize = 32768;
  const prgRom = new Uint8Array(prgRomSize);

  // Offset 0x0000 corresponds to CPU $8000
  // Offset 0x4000 corresponds to CPU $C000 (standard location for DPCM samples)
  const codeEntryOffset = 0x0000; // CPU $8000

  // Machine Code Assembly instructions:
  // Reset sequence:
  // $8000: 78          SEI
  // $8001: D8          CLD
  // $8002: A2 40       LDX #$40
  // $8004: 8E 17 40    STX $4017       ; disable frame IRQ
  // $8007: A2 FF       LDX #$FF
  // $8009: 9A          TXS             ; init stack
  // $800A: A9 00       LDA #$00
  // $800C: 8D 00 20    STA $2000       ; disable NMI
  // $800F: 8D 01 20    STA $2001       ; disable rendering
  // $8012: 8D 10 40    STA $4010       ; disable DMC IRQ

  // VBlank 1 wait:
  // $8015: 2C 02 20    BIT $2002
  // $8018: 10 FB       BPL $8015

  // VBlank 2 wait:
  // $801A: 2C 02 20    BIT $2002
  // $801D: 10 FB       BPL $801A

  // Set APU DMC registers:
  // Rate: $4010 = rateIndex (bits 0..3)
  // Sample Address: $4012 = sampleAddressRegister
  // Sample Length: $4013 = hardwareLengthRegister
  // Enable DMC: $4015 = #$1F (or #$10)

  const rateByte = dpcmResult.sampleAddressRegister !== undefined ? 0x0f : 0x0f; // Default high rate
  const addrByte = dpcmResult.sampleAddressRegister;
  const lenByte = dpcmResult.hardwareLengthRegister;

  const machineCode: number[] = [
    // Init CPU
    0x78,             // SEI
    0xd8,             // CLD
    0xa2, 0x40,       // LDX #$40
    0x8e, 0x17, 0x40, // STX $4017 (disable APU frame IRQ)
    0xa2, 0xff,       // LDX #$FF
    0x9a,             // TXS (Stack init)
    0xa9, 0x00,       // LDA #$00
    0x8d, 0x00, 0x20, // STA $2000 (disable NMI)
    0x8d, 0x01, 0x20, // STA $2001 (disable rendering)
    0x8d, 0x10, 0x40, // STA $4010 (disable DMC IRQ)

    // Wait vblank 1
    0x2c, 0x02, 0x20, // BIT $2002
    0x10, 0xfb,       // BPL -5

    // Wait vblank 2
    0x2c, 0x02, 0x20, // BIT $2002
    0x10, 0xfb,       // BPL -5

    // Configure DMC Registers
    0xa9, rateByte,   // LDA #rateByte (Playback frequency)
    0x8d, 0x10, 0x40, // STA $4010
    0xa9, addrByte,   // LDA #addrByte (Sample address offset: $C000 + A*64)
    0x8d, 0x12, 0x40, // STA $4012
    0xa9, lenByte,    // LDA #lenByte  (Sample length: (L*16)+1 bytes)
    0x8d, 0x13, 0x40, // STA $4013

    // Trigger DMC playback on boot
    0xa9, 0x1f,       // LDA #$1F (Enable DMC channel bit 4 + PSG channels)
    0x8d, 0x15, 0x40, // STA $4015 (Start DPCM playback!)

    // Main Interactive Loop (reads Joypad 1 at $4016):
    // Strobe joypad: LDA #1, STA $4016, LDA #0, STA $4016
    // If Button A pressed: restart sample
    // Poll loop:
    0xa9, 0x01,       // loop: LDA #1
    0x8d, 0x16, 0x40, // STA $4016
    0xa9, 0x00,       // LDA #0
    0x8d, 0x16, 0x40, // STA $4016 (latch joypad)

    0xad, 0x16, 0x40, // LDA $4016 (Button A)
    0x29, 0x01,       // AND #1
    0xf0, 0x0c,       // BEQ skip_play (skip 12 bytes if not pressed)

    // Restart sound on Button A
    0xa9, 0x00,       // LDA #0
    0x8d, 0x15, 0x40, // STA $4015 (disable)
    0xa9, 0x1f,       // LDA #$1F
    0x8d, 0x15, 0x40, // STA $4015 (re-trigger)

    // Delay loop / infinite idle
    // skip_play:
    0xea,             // NOP
    0x4c, 0x2e, 0x80, // JMP $802E (jump back to loop)
  ];

  // Write machine code at start of PRG-ROM ($8000)
  for (let i = 0; i < machineCode.length; i++) {
    prgRom[codeEntryOffset + i] = machineCode[i];
  }

  // Embed DPCM Sample Data at CPU $C000 (Offset 0x4000 in PRG-ROM)
  const dpcmPrgOffset = 0x4000;
  const sampleLength = Math.min(dpcmResult.dmcData.length, prgRomSize - dpcmPrgOffset - 16);
  for (let i = 0; i < sampleLength; i++) {
    prgRom[dpcmPrgOffset + i] = dpcmResult.dmcData[i];
  }

  // 6502 Hardware Interrupt Vector Table at the very end of PRG-ROM:
  // $FFFA: NMI vector   ($8000)
  // $FFFC: RESET vector ($8000)
  // $FFFE: IRQ vector   ($8000)
  const vectorOffset = prgRomSize - 6;
  // NMI Vector ($8000)
  prgRom[vectorOffset + 0] = 0x00;
  prgRom[vectorOffset + 1] = 0x80;
  // RESET Vector ($8000)
  prgRom[vectorOffset + 2] = 0x00;
  prgRom[vectorOffset + 3] = 0x80;
  // IRQ Vector ($8000)
  prgRom[vectorOffset + 4] = 0x00;
  prgRom[vectorOffset + 5] = 0x80;

  // 3. CHR-ROM (8 KB = 8,192 bytes)
  const chrRom = buildChrRomPatternTable();

  // Combine [16B Header] + [32KB PRG-ROM] + [8KB CHR-ROM]
  const totalRomSize = 16 + prgRom.length + (headerConfig.chrRomSize8k > 0 ? chrRom.length : 0);
  const nesRom = new Uint8Array(totalRomSize);

  // Copy Header
  nesRom.set(headerBytes, 0);
  // Copy PRG-ROM
  nesRom.set(prgRom, 16);
  // Copy CHR-ROM if enabled
  if (headerConfig.chrRomSize8k > 0) {
    nesRom.set(chrRom, 16 + prgRom.length);
  }

  return nesRom;
}
